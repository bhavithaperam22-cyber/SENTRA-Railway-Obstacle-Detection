import cv2

INTEREST_CLASSES=[
    "person",
    "dog",
    "cat",
    "cow",
    "horse",
    "sheep",
    "bird",
    "car",
    "truck",
    "bus",
    "motorcycle",
    "bicycle"
]

def detect_obstacles(image):

    results=yolo_model.predict(

        source=image,

        imgsz=640,

        conf=0.25,

        verbose=False

    )

    detections=[]

    for r in results:

        names=r.names

        for box in r.boxes:

            cls=int(box.cls)

            name=names[cls]

            if name not in INTEREST_CLASSES:
                continue

            x1,y1,x2,y2=map(int,box.xyxy[0])

            detections.append({

                "class":name,

                "conf":float(box.conf),

                "bbox":[x1,y1,x2,y2],

                "center":(

                    (x1+x2)//2,

                    (y1+y2)//2

                )

            })

    return detections

print("Obstacle Detector Ready")

