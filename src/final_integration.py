def filter_track_objects(mask,detections):

    track_objects=[]

    h,w=mask.shape

    for det in detections:

        cx,cy=det["center"]

        if cx<0 or cy<0:
            continue

        if cx>=w or cy>=h:
            continue

        if mask[cy,cx]>0:

            det["on_track"]=True

            track_objects.append(det)

        else:

            det["on_track"]=False

    return track_objects

print("Track Filter Ready")

