import math

def estimate_distance(det):

    x1,y1,x2,y2=det["bbox"]

    width=x2-x1
    height=y2-y1

    size=max(width,height)

    if size<1:
        size=1

    # Approximate distance (meters)
    distance=250/size

    return round(distance,2)


def get_risk(distance):

    if distance<3:

        return "HIGH",(0,0,255)

    elif distance<7:

        return "MEDIUM",(0,255,255)

    else:

        return "LOW",(0,255,0)


def analyse(track_objects):

    results=[]

    for det in track_objects:

        d=estimate_distance(det)

        risk,color=get_risk(d)

        det["distance"]=d

        det["risk"]=risk

        det["color"]=color

        results.append(det)

    return results

print("Risk Module Ready")

