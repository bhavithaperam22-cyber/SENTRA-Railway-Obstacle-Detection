import cv2
import numpy as np

def draw_results(image, rail_mask, results):

    output = image.copy()

    # Overlay rail mask
    green = np.zeros_like(output)
    green[:, :, 1] = rail_mask

    output = cv2.addWeighted(output, 1.0, green, 0.35, 0)

    for det in results:

        x1, y1, x2, y2 = det["bbox"]

        color = det["color"]

        cv2.rectangle(
            output,
            (x1, y1),
            (x2, y2),
            color,
            3
        )

        text = f'{det["class"]}'

        cv2.putText(
            output,
            text,
            (x1, y1-40),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.7,
            color,
            2
        )


        cv2.putText(
            output,
            det["risk"],
            (x1, y2+25),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.7,
            color,
            2
        )

        cx, cy = det["center"]

        cv2.circle(
            output,
            (cx, cy),
            5,
            (255,255,255),
            -1
        )

    return output

