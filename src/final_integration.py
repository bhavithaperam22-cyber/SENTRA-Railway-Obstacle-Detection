import os
import subprocess

class EgoPathDetector:

    def __init__(self):

        self.project="/content/train-ego-path-detection"

        self.weights=None

        weights_dir=os.path.join(
            self.project,
            "weights"
        )

        for root,dirs,files in os.walk(weights_dir):

            for f in files:

                if f.endswith(".pt"):

                    self.weights=os.path.join(root,f)

                    break

            if self.weights:
                break

        print("="*60)
        print("EGO PATH MODEL")
        print("="*60)

        print("Weights:",self.weights)

        if self.weights is None:
            raise FileNotFoundError("No EgoPath weights found!")

    def detect(self,image_path):

        output="/content/ego_output"

        if os.path.exists(output):

            import shutil
            shutil.rmtree(output)

        os.makedirs(output)

        command=[
            "python",
            os.path.join(self.project,"detect.py"),
            os.path.dirname(self.weights),
            image_path,
            "--output",
            output
        ]

        result=subprocess.run(
            command,
            cwd=self.project
        )

        images=[]

        for f in os.listdir(output):

            if f.endswith(".jpg") or f.endswith(".png"):

                images.append(
                    os.path.join(output,f)
                )

        if len(images)==0:

            return None

        images.sort()

        return images[-1]


